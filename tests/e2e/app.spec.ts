test('log attachment, support clipboard and exported diagnostics redact credentials', async ({}, testInfo) => {
  const page = await launch('no-admin')
  const dir = await mkdtemp(join(tmpdir(), 'easyai-dialog-'))
  const log = join(dir, 'sample.log'); const report = join(dir, 'diagnostics.json')
  await writeFile(log, 'Codex lỗi: api_key=sk-example-secret123\nHTTP_PROXY=http://bob:password@proxy:8080')
  await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }) }, log)
  await page.getByRole('button', { name: 'Đính kèm log' }).click()
  await expect(page.getByRole('textbox', { name: 'Nhập yêu cầu' })).toHaveValue(/\[REDACTED\]/)
  await expect(page.getByRole('textbox', { name: 'Nhập yêu cầu' })).not.toHaveValue(/secret123/)
  await page.getByRole('button', { name: 'Gửi yêu cầu' }).click()
  await expect(page.getByText('Cần đội ngũ IT hỗ trợ')).toBeVisible()
  await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, report)
  await page.getByRole('button', { name: 'Xuất chẩn đoán' }).click()
  await expect(page.getByRole('status')).toContainText('Đã xuất')
  const saved = await readFile(report, 'utf8'); expect(saved).not.toContain('secret123'); expect(saved).not.toContain('bob:password')
  expect(JSON.parse(saved).support.code).toBe('IT-001')
  await testInfo.attach('diagnostics', { body: saved, contentType: 'application/json' })
})
test('history persists across app restart and renderer has no Node access', async () => {
  const page = await launch('no-admin'); await page.getByRole('button', { name: /Cài đặt công cụ/ }).click()
  await expect(page.getByText('Cần đội ngũ IT hỗ trợ')).toBeVisible()
  expect(await page.evaluate(() => typeof (window as any).require)).toBe('undefined')
  const root = await app.evaluate(({ app }) => app.getPath('userData'))
  await app.close()
  app = await electron.launch({ args: [resolve('out/main/index.js'), '--demo'], env: { ...process.env, EASYAI_DATA_DIR: root, EASYAI_SCENARIO: 'no-admin' } })
  const next = await app.firstWindow(); await next.locator('.history-item').first().click()
  await expect(next.getByText('Cần đội ngũ IT hỗ trợ')).toBeVisible()
  await expect(next.getByRole('button', { name: 'Xác nhận và thực hiện' })).toHaveCount(0)
})
