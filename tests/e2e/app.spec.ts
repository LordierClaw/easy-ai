import { test, expect, _electron as electron, type ElectronApplication } from '@playwright/test'
import { mkdtemp, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { resolve, join } from 'node:path'
let app: ElectronApplication
async function launch(scenario: string) {
  const dir = await mkdtemp(join(tmpdir(), 'easyai-e2e-'))
  app = await electron.launch({ args: [resolve('out/main/index.js'), '--demo'], env: { ...process.env, EASYAI_DATA_DIR: dir, EASYAI_SCENARIO: scenario }, timeout: 30000 })
  const page = await app.firstWindow(); await expect(page.getByText('Công cụ sẵn sàng.')).toBeVisible(); return page
}
test.afterEach(async () => { await app?.close() })
test('guided install, approval, verification and explicit user confirmation', async ({}, testInfo) => {
  const page = await launch('success')
  await page.screenshot({ path: testInfo.outputPath('welcome.png'), fullPage: true })
  await page.getByRole('button', { name: /Cài đặt công cụ/ }).click()
  await expect(page.getByRole('button', { name: 'Xác nhận và thực hiện' })).toBeVisible()
  await page.getByRole('button', { name: 'Xác nhận và thực hiện' }).click()
  await expect(page.getByText('Hoàn tất đăng nhập')).toBeVisible()
  await page.getByRole('button', { name: 'Tôi đã dùng được ChatGPT' }).click()
  await expect(page.getByText('Bộ công cụ của bạn đã sẵn sàng')).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('ready.png'), fullPage: true })
})
